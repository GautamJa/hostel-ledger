import { jsPDF } from 'jspdf';

export interface PaymentReceiptData {
  receiptNumber: string;
  studentName: string;
  admissionNumber: string;
  roomNumber?: string;
  amount: string;
  paymentMethod: string;
  transactionReference?: string | null;
  paymentDate: string;
  remarks?: string | null;
  collectorName?: string;
}

export interface StudentAdmissionSlipData {
  admissionNumber: string;
  name: string;
  gender: string;
  dob?: string;
  email: string;
  phone: string;
  roomNumber?: string;
  monthlyFee: string;
  admissionDate: string;
  guardianName?: string;
  guardianPhone?: string;
  department?: string;
}

/**
 * Renders an authentic rotated watermark "Somnath" across the document page.
 */
export function drawSomnathWatermark(doc: jsPDF) {
  doc.saveGraphicsState();

  // Subtle slate-gray watermark that is distinct and legible without hindering text reading
  doc.setTextColor(218, 224, 233);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(54);

  // Large rotated watermark across document center
  doc.text('Somnath', 105, 155, { align: 'center', angle: 35 });

  // Secondary sub-stamp
  doc.setFontSize(12);
  doc.setTextColor(228, 233, 240);
  doc.text('SOMNATHRECORDERS • VERIFIED AUTHENTIC', 105, 172, { align: 'center', angle: 35 });

  doc.restoreGraphicsState();
}

export function generatePaymentReceiptPDF(data: PaymentReceiptData) {
  const doc = new jsPDF();

  // Header Banner
  doc.setFillColor(15, 23, 42); // slate-900
  doc.rect(0, 0, 210, 36, 'F');

  // Title: SomnathRecorders
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(18);
  doc.setFont('helvetica', 'bold');
  doc.text('SOMNATHRECORDERS', 105, 16, { align: 'center' });

  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(203, 213, 225); // slate-300
  doc.text('OFFICIAL PAYMENT RECEIPT & AUDIT VOUCHER', 105, 26, { align: 'center' });

  // Receipt Number & Date Box
  doc.setTextColor(15, 23, 42);
  doc.setFontSize(11);
  doc.setFont('helvetica', 'bold');
  doc.text(`Receipt #: ${data.receiptNumber}`, 16, 48);
  doc.setFont('helvetica', 'normal');
  doc.text(`Date of Issue: ${data.paymentDate}`, 145, 48);

  // Divider Line
  doc.setDrawColor(226, 232, 240);
  doc.setLineWidth(0.5);
  doc.line(16, 52, 194, 52);

  // Student Information Box
  doc.setFillColor(248, 250, 252);
  doc.rect(16, 56, 178, 38, 'F');
  doc.setDrawColor(203, 213, 225);
  doc.rect(16, 56, 178, 38, 'S');

  doc.setFontSize(10);
  doc.setFont('helvetica', 'bold');
  doc.text('RESIDENT DETAILS', 22, 64);

  doc.setFont('helvetica', 'normal');
  doc.text(`Student Name:`, 22, 72);
  doc.setFont('helvetica', 'bold');
  doc.text(`${data.studentName}`, 55, 72);

  doc.setFont('helvetica', 'normal');
  doc.text(`Admission ID:`, 22, 80);
  doc.setFont('helvetica', 'bold');
  doc.text(`${data.admissionNumber}`, 55, 80);

  doc.setFont('helvetica', 'normal');
  doc.text(`Allocated Room:`, 115, 72);
  doc.setFont('helvetica', 'bold');
  doc.text(`${data.roomNumber || 'Unassigned'}`, 150, 72);

  doc.setFont('helvetica', 'normal');
  doc.text(`Account Status:`, 115, 80);
  doc.setTextColor(5, 150, 105);
  doc.setFont('helvetica', 'bold');
  doc.text(`Verified Clean`, 150, 80);

  // Transaction Ledger Summary
  doc.setTextColor(15, 23, 42);
  doc.setFontSize(11);
  doc.setFont('helvetica', 'bold');
  doc.text('TRANSACTION PARTICULARS', 16, 106);

  // Table header (no dollar sign)
  doc.setFillColor(241, 245, 249);
  doc.rect(16, 110, 178, 10, 'F');
  doc.setFontSize(9);
  doc.text('DESCRIPTION', 22, 116);
  doc.text('METHOD', 100, 116);
  doc.text('REF / TXN ID', 135, 116);
  doc.text('AMOUNT', 175, 116, { align: 'right' });

  // Table row
  doc.setFont('helvetica', 'normal');
  doc.text('Fee Payment / Dues Settle', 22, 126);
  doc.text(`${data.paymentMethod.replace(/_/g, ' ').toUpperCase()}`, 100, 126);
  doc.text(`${data.transactionReference || 'N/A'}`, 135, 126);
  doc.setFont('helvetica', 'bold');
  doc.text(`${Number(data.amount).toFixed(2)}`, 175, 126, { align: 'right' });

  doc.setDrawColor(226, 232, 240);
  doc.line(16, 132, 194, 132);

  // Total Box
  doc.setFillColor(248, 250, 252);
  doc.rect(110, 136, 84, 22, 'F');
  doc.rect(110, 136, 84, 22, 'S');

  doc.setFontSize(10);
  doc.setFont('helvetica', 'bold');
  doc.text('TOTAL RECEIVED:', 116, 146);
  doc.setFontSize(14);
  doc.setTextColor(15, 23, 42);
  doc.text(`${Number(data.amount).toFixed(2)}`, 188, 148, { align: 'right' });

  // Remarks
  if (data.remarks) {
    doc.setFontSize(9);
    doc.setTextColor(100, 116, 139);
    doc.setFont('helvetica', 'italic');
    doc.text(`Remarks: ${data.remarks}`, 16, 170);
  }

  // Legal Audit Note
  doc.setFontSize(8);
  doc.setTextColor(148, 163, 184);
  doc.setFont('helvetica', 'normal');
  doc.text(
    'This receipt is an immutable system record generated by SomnathRecorders.',
    16,
    210
  );
  doc.text(
    'Old payment records are strictly append-only and cannot be altered or overwritten.',
    16,
    216
  );

  // Signature Blocks
  doc.setTextColor(15, 23, 42);
  doc.setDrawColor(15, 23, 42);
  doc.line(22, 250, 80, 250);
  doc.setFontSize(9);
  doc.setFont('helvetica', 'bold');
  doc.text('Authorized Accounts Officer', 22, 256);
  if (data.collectorName) {
    doc.setFontSize(8);
    doc.setFont('helvetica', 'normal');
    doc.text(`Issued by: ${data.collectorName}`, 22, 262);
  }

  doc.line(135, 250, 188, 250);
  doc.setFontSize(9);
  doc.setFont('helvetica', 'bold');
  doc.text('Resident Student Signature', 135, 256);

  // Official Stamp & Somnath Watermark
  doc.setFontSize(18);
  doc.setTextColor(226, 232, 240);
  doc.setFont('helvetica', 'bold');
  doc.text('PAID & VERIFIED', 105, 190, { align: 'center' });

  // Render "Somnath" Watermark
  drawSomnathWatermark(doc);

  // Save/Download
  doc.save(`Receipt-${data.receiptNumber}.pdf`);
}

export function generateAdmissionSlipPDF(data: StudentAdmissionSlipData) {
  const doc = new jsPDF();

  // Header Banner
  doc.setFillColor(15, 23, 42);
  doc.rect(0, 0, 210, 36, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(18);
  doc.setFont('helvetica', 'bold');
  doc.text('SOMNATHRECORDERS', 105, 16, { align: 'center' });

  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(203, 213, 225);
  doc.text('STUDENT ADMISSION & ROOM ALLOCATION SLIP', 105, 26, { align: 'center' });

  // Information Body
  doc.setTextColor(15, 23, 42);
  doc.setFontSize(12);
  doc.setFont('helvetica', 'bold');
  doc.text(`Admission No: ${data.admissionNumber}`, 16, 48);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.text(`Date of Admission: ${data.admissionDate}`, 140, 48);

  doc.setDrawColor(226, 232, 240);
  doc.line(16, 54, 194, 54);

  // Profile Card
  doc.setFillColor(248, 250, 252);
  doc.rect(16, 60, 178, 65, 'F');
  doc.rect(16, 60, 178, 65, 'S');

  doc.setFontSize(10);
  doc.setFont('helvetica', 'bold');
  doc.text('PERSONAL INFORMATION', 22, 68);

  const leftX = 22;
  const rightX = 110;

  doc.setFont('helvetica', 'normal');
  doc.text(`Full Name:`, leftX, 76);
  doc.setFont('helvetica', 'bold');
  doc.text(`${data.name}`, leftX + 25, 76);

  doc.setFont('helvetica', 'normal');
  doc.text(`Gender:`, leftX, 84);
  doc.setFont('helvetica', 'bold');
  doc.text(`${data.gender.toUpperCase()}`, leftX + 25, 84);

  doc.setFont('helvetica', 'normal');
  doc.text(`Contact:`, leftX, 92);
  doc.setFont('helvetica', 'bold');
  doc.text(`${data.phone}`, leftX + 25, 92);

  doc.setFont('helvetica', 'normal');
  doc.text(`Email:`, leftX, 100);
  doc.setFont('helvetica', 'bold');
  doc.text(`${data.email}`, leftX + 25, 100);

  if (data.department) {
    doc.setFont('helvetica', 'normal');
    doc.text(`Department:`, leftX, 108);
    doc.setFont('helvetica', 'bold');
    doc.text(`${data.department}`, leftX + 25, 108);
  }

  // Right column
  doc.setFont('helvetica', 'normal');
  doc.text(`Allocated Room:`, rightX, 76);
  doc.setFont('helvetica', 'bold');
  doc.text(`${data.roomNumber || 'Pending Allocation'}`, rightX + 35, 76);

  doc.setFont('helvetica', 'normal');
  doc.text(`Monthly Fee:`, rightX, 84);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(5, 150, 105);
  doc.text(`${Number(data.monthlyFee).toFixed(2)} / month`, rightX + 35, 84);
  doc.setTextColor(15, 23, 42);

  if (data.guardianName) {
    doc.setFont('helvetica', 'normal');
    doc.text(`Guardian:`, rightX, 92);
    doc.setFont('helvetica', 'bold');
    doc.text(`${data.guardianName}`, rightX + 35, 92);
  }

  if (data.guardianPhone) {
    doc.setFont('helvetica', 'normal');
    doc.text(`Guardian Contact:`, rightX, 100);
    doc.setFont('helvetica', 'bold');
    doc.text(`${data.guardianPhone}`, rightX + 35, 100);
  }

  // Terms & Rules
  doc.setFontSize(10);
  doc.setFont('helvetica', 'bold');
  doc.text('TERMS & RULES', 16, 140);

  const rules = [
    '1. Monthly fees must be settled before the last day of each calendar month.',
    '2. Automatic fee reminders are dispatched 1 day before the month-end deadline.',
    '3. Residents must maintain decorum, quiet hours, and facility cleanliness.',
    '4. Any property damage will be assessed and billed directly.',
    '5. Vacating notice must be filed in advance with the management office.',
  ];

  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  let y = 148;
  rules.forEach((rule) => {
    doc.text(rule, 16, y);
    y += 7;
  });

  // Signatures
  doc.setDrawColor(15, 23, 42);
  doc.line(22, 235, 80, 235);
  doc.setFontSize(9);
  doc.setFont('helvetica', 'bold');
  doc.text('Authorized Official Signature', 22, 242);

  doc.line(135, 235, 188, 235);
  doc.setFontSize(9);
  doc.setFont('helvetica', 'bold');
  doc.text('Student / Guardian Signature', 135, 242);

  // Render "Somnath" Watermark
  drawSomnathWatermark(doc);

  doc.save(`AdmissionSlip-${data.admissionNumber}.pdf`);
}
